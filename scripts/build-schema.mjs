// prisma/schema.src.prisma (camelCase) -> prisma/schema.prisma (snake_case @map).
import { readFileSync, writeFileSync } from 'node:fs'

const src = readFileSync('prisma/schema.src.prisma', 'utf8').split('\r\n').join('\n')
const snake = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toLowerCase()
const SPECIAL = {
  WorkspaceSettings: 'workspace_settings',
  ActivityLog: 'activity_log',
  AuditLog: 'audit_log',
  AiUsage: 'ai_usage',
  Faculty: 'faculties',
}
const plural = (name) =>
  SPECIAL[name] ??
  (() => {
    const s = snake(name)
    return /[^aeiou]y$/.test(s) ? s.slice(0, -1) + 'ies' : s + 's'
  })()

const SCALARS = new Set(['String', 'Int', 'BigInt', 'Boolean', 'DateTime', 'Json', 'Decimal', 'Bytes', 'Float'])
const enums = new Set([...src.matchAll(/^enum (\w+) \{/gm)].map((m) => m[1]))

const out = []
let block = null
for (const line of src.split('\n')) {
  const open = line.match(/^(model|enum) (\w+) \{/)
  if (open) {
    block = { kind: open[1], name: open[2] }
    out.push(line)
    continue
  }
  if (block && line === '}') {
    const table = block.kind === 'model' ? plural(block.name) : snake(block.name)
    out.push(`  @@map("${table}")`, '}')
    block = null
    continue
  }
  if (block?.kind === 'model') {
    const m = line.match(/^(\s{2})(\w+)(\s+)([A-Za-z]+)(\?|\[\])?(.*)$/)
    if (m && !line.trim().startsWith('//') && !line.trim().startsWith('@@')) {
      const [, ind, field, gap, type, mod, rest] = m
      const scalar = SCALARS.has(type) || enums.has(type)
      if (scalar && snake(field) !== field && !rest.includes('@map(')) {
        // keep any trailing // comment last
        const [attrs, comment] = rest.split(/\s+\/\/ /)
        out.push(`${ind}${field}${gap}${type}${mod ?? ''}${attrs} @map("${snake(field)}")${comment ? ' // ' + comment : ''}`)
        continue
      }
    }
  }
  out.push(line)
}
const header = '// GENERATED by scripts/build-schema.mjs from schema.src.prisma. Do not edit.\n'
writeFileSync('prisma/schema.prisma', header + out.join('\n'))
console.log('prisma/schema.prisma written')
